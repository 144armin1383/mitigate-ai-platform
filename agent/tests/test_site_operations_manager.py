class FakeAutonomousDevelopmentSupervisor:
    def __init__(self) -> None:
        self.submitted: List[Dict[str, Any]] = []

    def start(self, project_id: str, objective: str, allowed_paths: List[str], denied_paths: List[str], risk: str, acceptance_criteria: List[str], validation_requirements: List[str]) -> str:
        run_id = f"run-{len(self.submitted)+1:06d}"
        self.submitted.append({
            "project_id": project_id,
            "objective": objective,
            "allowed_paths": list(allowed_paths),
            "denied_paths": list(denied_paths),
            "risk": risk,
            "acceptance_criteria": list(acceptance_criteria),
            "validation_requirements": list(validation_requirements),
            "run_id": run_id,
        })
        return run_id


